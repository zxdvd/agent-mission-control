import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const base=process.env.AMC_URL||'http://127.0.0.1:8787';
if(!['127.0.0.1','localhost','[::1]'].includes(new URL(base).hostname)) throw new Error('Local QA only');
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const errors=[];let checks=0;
function pass(text){checks++;console.log('PASS',text);}
const page=await browser.newPage({viewport:{width:1440,height:1100}});
page.on('pageerror',error=>errors.push(error.message));
await page.goto(base,{waitUntil:'networkidle'});
await page.getByRole('heading',{name:'Attention inbox',exact:true}).waitFor();
await page.getByRole('button',{name:'Ship design system tokens',exact:true}).waitFor();
pass('desktop renders real D1 task and attention data');
await page.screenshot({path:'/tmp/amc-desktop-dark.png',fullPage:true});
await page.getByRole('button',{name:/switch to light/i}).click();
await page.screenshot({path:'/tmp/amc-desktop-light.png',fullPage:true});
assert.equal(await page.locator('html').getAttribute('data-theme'),'light');pass('light theme toggles and renders');
await page.reload({waitUntil:'networkidle'});assert.equal(await page.locator('html').getAttribute('data-theme'),'light');pass('theme preference persists across reload');
await page.getByLabel('Search tasks',{exact:true}).fill('semantic-tokens');
await page.getByRole('button',{name:'Ship design system tokens',exact:true}).waitFor();
assert.equal(await page.locator('.task-table tbody tr').count(),1);pass('task search filters repo/branch metadata');
await page.getByRole('button',{name:'Ship design system tokens',exact:true}).click();
await page.getByRole('heading',{name:'Event timeline',exact:true}).waitFor();
await page.getByRole('button',{name:'Rename task',exact:true}).click();
await page.getByLabel('Task name',{exact:true}).fill('Ship semantic tokens · reviewed');
await page.getByRole('button',{name:'Save',exact:true}).click();
await page.getByRole('heading',{name:'Ship semantic tokens · reviewed',exact:true}).waitFor();pass('task rename persists through real mutation API');
await page.getByRole('tab',{name:'Runs & sessions'}).click();
await page.getByRole('heading',{name:'Run history',exact:true}).waitFor();pass('run/session history accessible');
await page.getByRole('tab',{name:'Context',exact:true}).click();
await page.getByRole('button',{name:'Archive',exact:true}).click();
await page.getByRole('button',{name:'Restore',exact:true}).waitFor();
await page.getByRole('button',{name:'Restore',exact:true}).click();
await page.getByRole('button',{name:'Archive',exact:true}).waitFor();pass('archive/restore round trip succeeds');
await page.getByRole('button',{name:'Close task details'}).click();
assert.equal(await page.getByRole('dialog').count(),0);pass('detail close restores dashboard');
await page.getByRole('button',{name:'Clear search',exact:true}).click();
await page.getByRole('button',{name:/Mark approval requested as read/i}).first().click();
await page.getByRole('button',{name:/Attention inbox/}).first().click();
await page.getByRole('button',{name:/^Read\d*$/}).click();
await page.locator('.attention-card').first().waitFor();pass('attention read state survives API refresh');
await page.getByRole('button',{name:'Hosts',exact:true}).click();
await page.getByRole('heading',{name:'Studio · macOS',exact:true}).waitFor();pass('hosts screen displays heartbeat and session counts');
await page.screenshot({path:'/tmp/amc-hosts.png',fullPage:true});
const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
mobile.on('pageerror',error=>errors.push(error.message));
await mobile.goto(base,{waitUntil:'networkidle'});
await mobile.getByRole('heading',{name:'Attention inbox',exact:true}).waitFor();
assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'mobile page overflows horizontally');
await mobile.screenshot({path:'/tmp/amc-mobile.png',fullPage:true});pass('390px mobile layout fits viewport');
await mobile.getByRole('button',{name:'Open navigation'}).click();
await mobile.getByRole('button',{name:'Hosts',exact:true}).click();
await mobile.getByRole('heading',{name:'Studio · macOS',exact:true}).waitFor();pass('mobile navigation opens, navigates and closes');
assert.equal(errors.length,0,errors.join('\n'));pass('no browser runtime errors');
await browser.close();console.log(`\n${checks} browser checks passed.`);
